def fig_ladder(lad: pd.DataFrame, cells: list[str], fdir: Path, name: str, title: str,
               order: list[str], cstars: dict) -> str | None:
    lad = lad[lad.cell.isin(cells)]
    if lad.empty:
        return None
    plt = _plt()
    cl = [c for c in cells if c in set(lad.cell)]
    fig, axes = plt.subplots(1, len(cl), figsize=(min(2.6 * len(cl), 7.0), 2.6), squeeze=False)
    for ax, c in zip(axes[0], cl):
        d = lad[lad.cell == c]
        labs = [x for x in order if x in set(d.label) and x != "L0"]
        hs = [h for h in d.horizon.unique() if h != "pooled"]
        for j, h in enumerate(sorted(hs, key=int) + ["pooled"]):
            v = d[d.horizon == h].set_index("label").reindex(labs).wis_log
            sty = dict(color="black", lw=1.6, marker="s", ms=4) if h == "pooled" else \
                dict(color=OI[j % len(OI)], lw=1.0, marker="o", ms=3)
            ax.plot(range(len(labs)), v.to_numpy(), label="pooled h" if h == "pooled" else f"h{h}", **sty)
        ax.set_xticks(range(len(labs)))
        ax.set_xticklabels([x.replace("C*", f"{cstars.get(c) or 'C*'}") for x in labs],
                           rotation=45, ha="right")
        l0 = d[(d.label == "L0") & (d.horizon == "pooled")].wis_log
        sub = f"\nL0 naive (off scale) = {l0.iloc[0]:.3f}" if len(l0) else ""
        ax.set_title(f"{c}{sub}", loc="left")
    axes[0][0].set_ylabel("mean log1p WIS (lower = better)")
    hl, ll = axes[0][0].get_legend_handles_labels()
    fig.legend(hl, ll, loc="lower center", ncol=len(ll), frameon=False, bbox_to_anchor=(0.5, -0.06))
    fig.suptitle(title, x=0.01, ha="left", fontsize=8.5)
    fig.tight_layout()
    _save(fig, fdir, name)
    return name


def fig_per_year(est: pd.DataFrame, cells: list[str], fdir: Path) -> str | None:
    d = est[(est.stratum == "all") & (est.horizon == "pooled") & (est.test_year != "pooled")
            & est.estimand.isin(["G_emb", "G_excess"]) & est.cell.isin(cells)]
    if d.empty:
        return None
    plt = _plt()
    cl = [c for c in cells if c in set(d.cell)]
    fig, axes = plt.subplots(1, len(cl), figsize=(min(2.5 * len(cl), 7.0), 2.5), squeeze=False,
                             sharey=False)
    for ax, c in zip(axes[0], cl):
        ax.axhspan(-1, 1, color=OI[4], alpha=0.15, lw=0)
        ax.axhline(0, color="#444444", lw=0.8)
        for j, (e, off) in enumerate((("G_emb", -0.12), ("G_excess", 0.12))):
            x = d[(d.cell == c) & (d.estimand == e)].sort_values("test_year")
            yrs = x.test_year.astype(int).to_numpy()
            w = x.wis_ref.astype(float).to_numpy()
            p = 100 * x.estimate.astype(float).to_numpy() / w
            lo = 100 * x.lo95.astype(float).to_numpy() / w
            hi = 100 * x.hi95.astype(float).to_numpy() / w
            ax.errorbar(yrs + off, p, yerr=[p - lo, hi - p], fmt="o", ms=3.5, lw=1, capsize=0,
                        color=OI[j], label=e)
        ax.set_title(c, loc="left")
        ax.set_ylabel("% of WIS(L3)")
        ax.xaxis.set_major_locator(__import__("matplotlib").ticker.MaxNLocator(integer=True))
    axes[0][0].set_ylabel("% of WIS(L3)  (positive = AlphaEarth helps)")
    for ax in axes[0][1:]:
        ax.set_ylabel("")
    hl, ll = axes[0][0].get_legend_handles_labels()
    fig.legend(hl, ll, loc="lower center", ncol=2, frameon=False, bbox_to_anchor=(0.5, -0.06))
    fig.suptitle("F3. Per-test-year G_emb and G_excess (95% CI; band = ±1%)", x=0.01, ha="left",
                 fontsize=8.5)
    fig.tight_layout()
    _save(fig, fdir, "F3_per_year_gains")
    return "F3_per_year_gains"
