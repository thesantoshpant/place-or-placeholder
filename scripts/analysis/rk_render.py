# Okabe-Ito (colour-blind safe), fixed order; grey for secondary / reference marks
OI = ["#0072B2", "#E69F00", "#009E73", "#CC79A7", "#56B4E9", "#D55E00", "#F0E442", "#000000"]
GREY = "#7F7F7F"


# ------------------------------------------------------------------ table writers
def _fmt(v, nd=5):
    if v is None or (isinstance(v, float) and not np.isfinite(v)):
        return ""
    if isinstance(v, (float, np.floating)):
        return f"{v:.{nd}f}"
    s = str(v)
    return "" if s in ("nan", "None", "NaN") else s


def _tex_escape(s: str) -> str:
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("_", r"\_"),
                 ("#", r"\#"), ("$", r"\$"), ("±", r"$\pm$"), ("*", r"$^{*}$")):
        s = s.replace(a, b)
    return s


def to_booktabs(df: pd.DataFrame, caption: str, label: str, nd: int = 4) -> str:
    cols = list(df.columns)
    align = "".join("r" if pd.api.types.is_numeric_dtype(df[c]) else "l" for c in cols)
    out = [f"% {caption}", f"% generated by scripts/analysis/make_results.py; label {label}",
           f"\\begin{{tabular}}{{{align}}}", "\\toprule",
           " & ".join(_tex_escape(str(c)) for c in cols) + r" \\", "\\midrule"]
    for _, r in df.iterrows():
        out.append(" & ".join(_tex_escape(_fmt(r[c], nd)) for c in cols) + r" \\")
    out += ["\\bottomrule", "\\end{tabular}", ""]
    return "\n".join(out)


def write_table(df: pd.DataFrame, tdir: Path, name: str, caption: str, nd: int = 4,
                tex_cols: list[str] | None = None) -> str:
    tdir.mkdir(parents=True, exist_ok=True)
    df.to_csv(tdir / f"{name}.csv", index=False)
    t = df[tex_cols] if tex_cols else df
    (tdir / f"{name}.tex").write_text(to_booktabs(t, caption, f"tab:{name}", nd))
    return name


# ------------------------------------------------------------------ figure style
def _plt():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.size": 8, "axes.titlesize": 8.5, "axes.labelsize": 8,
                         "legend.fontsize": 7, "xtick.labelsize": 7, "ytick.labelsize": 7,
                         "axes.spines.top": False, "axes.spines.right": False,
                         "axes.grid": True, "grid.color": "#E5E5E5", "grid.linewidth": 0.5,
                         "axes.axisbelow": True, "pdf.fonttype": 42, "savefig.dpi": 200})
    return plt


def _save(fig, fdir: Path, name: str):
    fdir.mkdir(parents=True, exist_ok=True)
    fig.savefig(fdir / f"{name}.pdf", bbox_inches="tight")
    fig.savefig(fdir / f"{name}.png", bbox_inches="tight", dpi=200)
    import matplotlib.pyplot as plt
    plt.close(fig)


def fig_forest(t1: pd.DataFrame, sec: pd.DataFrame, fdir: Path) -> str:
    """F1: G_excess as % of WIS(ref), 95% (thin) and 90% (thick) CI, +-1% band."""
    plt = _plt()
    rows = [(f"{r.cell}", r, True) for r in t1.itertuples()] + \
           [(f"{r.cell}", r, False) for r in sec.itertuples()]
    n = len(rows)
    fig, ax = plt.subplots(figsize=(6.0, 0.24 * n + 1.0))
    ax.axvspan(-1, 1, color=OI[4], alpha=0.15, lw=0, label="±1% equivalence margin")
    ax.axvline(0, color="#444444", lw=0.8)
    for i, (lab, r, prim) in enumerate(rows):
        y = n - 1 - i
        if r.status != "available" or not np.isfinite(r.pct):
            ax.text(0, y, "pending", ha="center", va="center", fontsize=6.5, color=GREY,
                    style="italic", bbox=dict(fc="white", ec="none", pad=0.5))
            continue
        c = OI[0] if prim else GREY
        ax.plot([r.lo95_pct, r.hi95_pct], [y, y], color=c, lw=1.0)
        ax.plot([r.lo90_pct, r.hi90_pct], [y, y], color=c, lw=3.0, solid_capstyle="butt")
        ax.plot(r.pct, y, "o", ms=4.5, color=c, mec="white", mew=0.8)
    ax.set_yticks(range(n))
    ax.set_yticklabels([lab for lab, _, _ in rows][::-1])
    for tl, (_, _, prim) in zip(ax.get_yticklabels()[::-1], rows):
        tl.set_color("black" if prim else GREY)
    if len(t1) and len(sec):
        ax.axhline(n - len(t1) - 0.5, color="#BBBBBB", lw=0.6, ls="--")
    ax.set_xlabel("G_excess = WIS(L3+C*) − WIS(L4+C*), % of WIS(L3)   (positive = AlphaEarth helps)")
    ax.set_title("F1. Excess embedding gain beyond the best ID control (pooled over horizons)\n"
                 "dot = estimate, thick = 90% CI (TOST), thin = 95% CI; blue = primary family, "
                 "grey = secondary", loc="left")
    ax.legend(loc="lower right", frameon=False)
    ax.grid(axis="y", visible=False)
    _save(fig, fdir, "F1_forest_G_excess")
    return "F1_forest_G_excess"


