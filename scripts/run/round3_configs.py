#!/usr/bin/env python
"""Round-3 post hoc runs (EXP-B, docs/methods/round3_runs.md): configs + scheduler tier T6 manifest.

    python scripts/run/round3_configs.py gen             # write every static config (idempotent)
    python scripts/run/round3_configs.py list            # T6 items in priority order
    python scripts/run/round3_configs.py stages ITEM     # pipeline stages of one item (r3_pipeline.sh)
    python scripts/run/round3_configs.py pd ITEM         # pipeline state dir of one item
    python scripts/run/round3_configs.py tune CFG        # tuning only (writes <run dir>/tuning_<run>.json)
    python scripts/run/round3_configs.py gen-cstar-nohist   # CO S2 no-history N3/N4 + C* configs

Items: S1 extra seeds 1-2 (primary cells), S2 Taiwan S1 2021 ladder + control panel, S3 Colombia
S2 no-history arm, S4 Colombia S1 equal-budget tuning, plus EXP-A's variant configs listed in
runs/queue/r3_expA_configs.txt (one item per config, inserted after the CO S1 / CO S2 seed items).
A config is never overwritten with different content (gen refuses; move the old one aside first).
"""
from __future__ import annotations

import copy
import json
import sys
from pathlib import Path

import yaml

ROOT = Path("/net/home/spant/0-100/group-research/place-or-placeholder")
EXPA_LIST = ROOT / "runs/queue/r3_expA_configs.txt"
H14 = [1, 4]
ROLES = ("L3", "L4", "L3_Cstar", "L4_Cstar")
CSTAR_ONLY = ("L3_Cstar", "L4_Cstar")

# cell -> (config prefix of the seed-0 runs, new prefix, roles, test years override, seed-0 run dirs
# per role (ETA reference timings))
SEED_CELLS = {
    "co_s1": ("colombia_s1_shared_", "colombia_s1_r3_", ROLES, None,
              {"L3": "runs/colombia_s1_L3", "L4": "runs/colombia_s1_L4"}),
    "co_s2": ("colombia_s2_", "colombia_s2_r3_", ROLES, None, {}),
    "br_s5": ("brazil_s5_", "brazil_s5_r3_", ROLES, None, {}),
    # compute cut (docs/methods/round3_runs.md): TW S5 / PE S5 run C* roles only
    "tw_s5": ("taiwan_s5_", "taiwan_s5_r3_", CSTAR_ONLY, [2020, 2021, 2022, 2023, 2024], {}),
    "pe_s5": ("peru_s5_", "peru_s5_r3_", CSTAR_ONLY, None, {}),
    "co_s3": ("colombia_s3_", "colombia_s3_r3_", ROLES, None, {}),
    "co_s4": ("colombia_s4_", "colombia_s4_r3_", ROLES, None, {}),
    "pe_s1": ("peru_s1_shared_", "peru_s1_r3_", ROLES, None,
              {"L4": "runs/peru_s1_L4", "L4_Cstar": "runs/peru_s1_L4_Cstar"}),
    "tw_s1": ("taiwan_s1_shared_", "taiwan_s1_r3_", ROLES, [2020, 2021, 2022, 2023, 2024], {}),
}
TW_PANEL = [f"panel_{l}_{k}" for k in ("C2", "C3", "C6") for l in ("L3", "L4")]
TUNE_GRID = {"num_leaves": [15, 31, 127], "min_data_in_leaf": [100, 1000, 5000],
             "feature_fraction": [0.3, 0.9]}
TUNE_BASE = {"learning_rate": 0.05, "num_boost_round": 400, "bagging_fraction": 0.8,
             "bagging_freq": 1, "lambda_l2": 1.0}
NOHIST = "colombia_s2_nohist_"
NOHIST_CANDIDATES = ["C2", "C3", "C4", "C4s"]  # target-free; C6 only in S1 (nohist_arm.md)
SEEDED = ("C3", "C4", "C4s")


def _load(stem):
    return yaml.safe_load((ROOT / "configs" / f"{stem}.yaml").read_text())


def _write(stem, d, note):
    p = ROOT / "configs" / f"{stem}.yaml"
    hdr = (f"# Round-3 post hoc run (EXP-B, docs/methods/round3_runs.md): {note}\n"
           "# Generated by scripts/run/round3_configs.py; 4 threads.\n")
    txt = hdr + yaml.safe_dump(d, sort_keys=False)
    if p.exists():
        if p.read_text() == txt:
            return
        raise SystemExit(f"{p} exists with different content; move it aside first")
    p.write_text(txt)
    print("wrote", p.relative_to(ROOT))


# ------------------------------------------------------------------ configs
def seed_stem(cell, s, role):
    return f"{SEED_CELLS[cell][1]}seed{s}_{role}"


def gen_seeds():
    for cell, (src, new, roles, years, _) in SEED_CELLS.items():
        for s in (1, 2):
            for role in roles:
                d = _load(f"{src}{role}")
                d["exp_name"] = seed_stem(cell, s, role)
                d["seeds"] = [s]
                d["horizons"] = H14
                d["threads"] = 4
                if years:
                    d["test_years"] = years
                assert len(d["runs"]) == 1 and d["runs"][0].get("params_from"), d["runs"]
                _write(d["exp_name"], d, f"{d['runs'][0]['level']}, seed {s}, h1/h4; copy of "
                       f"configs/{src}{role}.yaml" + (f"; test years {years}" if years else ""))


def gen_tw_ladder():
    b = _load("taiwan_s1_baselines")
    b.update(exp_name="taiwan_s1_r3_tw2021_baselines", test_years=[2021], horizons=H14, threads=4)
    for r in b["runs"]:
        if r["model"] == "lgbm":  # the frozen Taiwan L1 tuning instead of re-tuning in a new dir
            r.pop("tune", None)
            r["params"] = {}
            r["name"] = "lgbm-L1"
            r["seeded"] = False
            r["params_from"] = "runs/taiwan_s1_baselines/tuning_lgbm-L1.json"
    _write(b["exp_name"], b, "Taiwan S1 baselines (L0, NB-L1, LGBM-L1), test year 2021, h1/h4")
    for n in ["L2"] + TW_PANEL:
        d = _load(f"taiwan_s1_shared_L2" if n == "L2" else f"taiwan_s1_{n}")
        d.update(exp_name=f"taiwan_s1_r3_tw2021_{n}", test_years=[2021], horizons=H14, threads=4)
        _write(d["exp_name"], d, f"Taiwan S1 {n}, test year 2021, h1/h4")


def gen_tuned():
    for lvl in ("L3", "L4"):
        d = _load(f"colombia_s1_shared_{lvl}_Cstar")
        r = d["runs"][0]
        assert r["level"] == f"{lvl}+C1", r
        r.pop("params_from")
        r["params"] = dict(TUNE_BASE)
        r["tune"] = {"grid": copy.deepcopy(TUNE_GRID), "horizons": list(H14), "quantiles": [0.1, 0.5, 0.9]}
        d.update(exp_name=f"colombia_s1_r3_tuned_{lvl}_Cstar", horizons=H14, threads=4, seeds=[0])
        _write(d["exp_name"], d, f"CO S1 {lvl}+C1 tuned for itself (equal-budget grid, train 2018 -> "
               "validate 2019), test years 2020-22, h1/h4")


def nohist_base(name, years, seeds, runs):
    tmpl = _load("colombia_s2_L4_Cstar")  # CO S2 features (LST screen, AE, control kwargs)
    return {"exp_name": f"{NOHIST}{name}", "country": "COLOMBIA", "panel": tmpl["panel"],
            "split": tmpl["split"], "test_years": years, "tune_year": 2019, "horizons": H14,
            "quantiles": tmpl["quantiles"], "coverage_levels": tmpl["coverage_levels"],
            "exclude_flag_gap": True, "seeds": seeds, "threads": 4, "features": tmpl["features"],
            "runs": runs}


def nohist_lg(level):
    k = level.split("+")[1] if "+" in level else None
    return {"model": "lgbm", "level": level, "name": f"lgbm-{level}", "seeded": k in SEEDED,
            "params_from": "runs/colombia_s1_baselines/tuning_lgbm-L1.json"}


def gen_nohist():
    tmpl = _load("colombia_s2_L4_Cstar")
    assert tmpl["split"]["name"] == "S2" and tmpl["test_years"] == [2020, 2021, 2022]
    ck = tmpl["features"]["control_kw"]
    assert ck["C4s"]["range_km"] != ck["C4"]["range_km"], ck  # C4s is a distinct candidate in CO
    _write(f"{NOHIST}controls_2019",
           nohist_base("controls_2019", [2019], [0, 1, 2],
                       [nohist_lg("N3")] + [nohist_lg(f"N3+{k}") for k in NOHIST_CANDIDATES]),
           f"Colombia S2 NO-HISTORY arm (exploratory): choice of C* among {NOHIST_CANDIDATES} at the "
           "2019 origin (C3/C4/C4s 3 seeds)")
    for lvl in ("N3", "N4", "N3+C1", "N4+C1"):
        n = lvl.replace("+", "_")
        _write(f"{NOHIST}{n}", nohist_base(n, [2020, 2021, 2022], [0], [nohist_lg(lvl)]),
               f"Colombia S2 NO-HISTORY arm (exploratory): LightGBM {lvl}")


def gen_cstar_nohist():
    sel = ROOT / f"runs/{NOHIST}controls_2019/selection.json"
    k = json.loads(sel.read_text())["c_star"]
    assert k in NOHIST_CANDIDATES, k
    for lvl in ("N3", "N4"):
        n = f"{lvl}_Cstar"
        _write(f"{NOHIST}{n}", nohist_base(n, [2020, 2021, 2022], [0], [nohist_lg(f"{lvl}+{k}")]),
               f"Colombia S2 NO-HISTORY arm (exploratory): LightGBM {lvl}+C* with C* = {k} (1 seed)")


def gen_all():
    gen_seeds()
    gen_tw_ladder()
    gen_tuned()
    gen_nohist()


# ------------------------------------------------------------------ tuning only
def tune_only(cfg_path):
    import os
    for v in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS", "NUMEXPR_NUM_THREADS"):
        os.environ[v] = "4"
    sys.path.insert(0, str(ROOT / "src"))
    from pop import runner
    cfg = runner.load_config(cfg_path)
    assert all(r.get("tune") for r in cfg["runs"]), "tune: every run needs a tune block"
    out = ROOT / cfg["runs_dir"] / cfg["exp_name"]
    out.mkdir(parents=True, exist_ok=True)
    cfg["panel"] = str(ROOT / cfg["panel"])
    datas, _ = runner.prepare_data(cfg, ROOT)
    print(json.dumps(runner._tune_all(cfg, datas, out), indent=1))


# ------------------------------------------------------------------ T6 manifest
def _seed_item(cell):
    src, new, roles, _, ref = SEED_CELLS[cell]
    order = [r for r in CSTAR_ONLY if r in roles] + [r for r in roles if r not in CSTAR_ONLY]
    st, refs = [], {}
    for role in order:
        for s in (1, 2):
            stem = seed_stem(cell, s, role)
            st.append(("run", stem, f"configs/{stem}.yaml"))
            dirs = [ref.get(role, f"runs/{src}{role}")]
            if cell in ("tw_s5", "tw_s1"):  # the 2021 runs of the seed-0 cell
                dirs.append(f"runs/{'taiwan_s5' if cell == 'tw_s5' else 'taiwan_s1'}_tw2021_{role}")
            refs[stem] = (dirs, 1.0, None)
    return {"id": f"r3_{cell}_seeds", "stages": st, "ref": refs}


def _tw_ladder_item():
    st, refs = [], {}
    for n in ["baselines", "L2"] + TW_PANEL:
        stem = f"taiwan_s1_r3_tw2021_{n}"
        st.append(("run", stem, f"configs/{stem}.yaml"))
        refs[stem] = ([f"runs/taiwan_s1_{'shared_L2' if n == 'L2' else n}"], 1.0, None)
    return {"id": "r3_tw_s1_ladder2021", "stages": st, "ref": refs}


def _tune_item():
    st, refs = [], {}
    for lvl in ("L3", "L4"):
        stem = f"colombia_s1_r3_tuned_{lvl}_Cstar"
        st.append(("py", f"tune_{stem}", f"scripts/run/round3_configs.py tune configs/{stem}.yaml"))
    for lvl in ("L3", "L4"):
        stem = f"colombia_s1_r3_tuned_{lvl}_Cstar"
        st.append(("run", stem, f"configs/{stem}.yaml"))
        refs[stem] = ([f"runs/colombia_s1_shared_{lvl}_Cstar"], 1.0, None)
    return {"id": "r3_co_s1_tuning", "stages": st, "ref": refs}


def _nohist_item():
    st = [("run", f"{NOHIST}controls_2019", f"configs/{NOHIST}controls_2019.yaml"),
          ("py", "select_control", f"scripts/run/select_control.py runs/{NOHIST}controls_2019 --ref lgbm-N3"),
          ("py", "gen_cstar", "scripts/run/round3_configs.py gen-cstar-nohist")]
    refs = {f"{NOHIST}controls_2019": (["runs/colombia_s2_controls_2019"], 1.0, None)}
    for n, src, f, tmpl in (("N3", "L3", 1.0, None), ("N4", "L4", 1.0, None),
                            ("N3_Cstar", "L3", 2.0, f"configs/{NOHIST}N3.yaml"),
                            ("N4_Cstar", "L4", 1.6, f"configs/{NOHIST}N4.yaml"),
                            ("N3_C1", "L3_Cstar", 1.0, None), ("N4_C1", "L4_Cstar", 1.0, None)):
        stem = f"{NOHIST}{n}"
        st.append(("run", stem, f"configs/{stem}.yaml"))
        refs[stem] = ([f"runs/colombia_s2_{src}"], f, tmpl)
    return {"id": "r3_co_s2_nohist", "stages": st, "ref": refs}


def expa_configs():
    """Config paths listed by EXP-A (one per line; '#' comments; only existing .yaml files)."""
    if not EXPA_LIST.exists():
        return []
    out = []
    for line in EXPA_LIST.read_text().splitlines():
        tok = line.split("#", 1)[0].strip().split()
        if not tok:
            continue
        p = tok[0]
        if not p.endswith(".yaml"):
            p += ".yaml"
        if not p.startswith("configs/"):
            p = "configs/" + Path(p).name
        if (ROOT / p).exists() and p not in out:
            out.append(p)
    return out


def _expa_item(cfg):
    """One T6 item per EXP-A config; ETA reference = the seed-0 run of the matching role."""
    import re
    stem = Path(cfg).stem
    ref = {}
    m = re.fullmatch(r"([a-z]+)_(s\d)_r3_V\d_(L3_Cstar|L3|L2)", stem)
    if m:
        c, s, role = m.groups()
        role = "L3" if role == "L2" else role
        dirs = ([f"runs/{c}_s1_shared_{role}", f"runs/{c}_s1_{role}"] if s == "s1"
                else [f"runs/{c}_{s}_{role}"])
        if c == "taiwan" and s == "s1":
            dirs.append(f"runs/taiwan_s1_tw2021_{role}")
        ref[stem] = (dirs, 1.0, None)
    return {"id": f"r3a_{stem}", "stages": [("run", stem, cfg)], "ref": ref}


def items():
    L = [_seed_item("co_s1"), _seed_item("co_s2")]
    L += [_expa_item(c) for c in expa_configs()]
    L += [_seed_item("br_s5"), _tw_ladder_item(), _seed_item("tw_s5"), _seed_item("pe_s5"),
          _tune_item(), _nohist_item(), _seed_item("co_s3"), _seed_item("co_s4"),
          _seed_item("pe_s1"), _seed_item("tw_s1")]
    for it in L:
        it["pd"] = f"runs/r3/{it['id']}"
    return L


def item(iid):
    if iid.startswith("cfg:"):
        it = _expa_item(iid[4:])
        it["pd"] = f"runs/r3/{it['id']}"
        return it
    for it in items():
        if it["id"] == iid:
            return it
    raise SystemExit(f"unknown item {iid}")


def main():
    a = sys.argv[1:]
    if not a:
        sys.exit(__doc__)
    import os
    os.chdir(ROOT)
    if a[0] == "gen":
        gen_all()
    elif a[0] == "gen-cstar-nohist":
        gen_cstar_nohist()
    elif a[0] == "tune":
        tune_only(a[1])
    elif a[0] == "list":
        for it in items():
            print(it["id"], " ".join(s[1] for s in it["stages"]))
    elif a[0] == "stages":
        for k, n, arg in item(a[1])["stages"]:
            print(k, n, arg)
    elif a[0] == "pd":
        print(item(a[1])["pd"])
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
